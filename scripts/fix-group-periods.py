# Leer el JSON actual para mantener el orden de participaciones por periodo
with open(r'c:\Users\jpsga\anestesiadelvalle\seed-group-periods.json', 'r', encoding='utf-8') as f:
    current = json.load(f)

result = []
for fecha, motivo, col_idx in periodos_def:
    # Buscar el periodo actual para mantener los OIDs y su orden
    current_periodo = next((p for p in current if p['fechaInicio']['$date'] == fecha), None)
    if not current_periodo:
        print(f'WARNING: periodo {fecha} no encontrado en JSON actual')
        continue

    participaciones = []
    for p in current_periodo['participaciones']:
        oid = p['userId']['$oid']
        key = oid_to_key.get(oid)
        if key is None:
            print(f'WARNING: OID {oid} no mapeado')
            continue
        pct = docx_pct[key][col_idx]
        participaciones.append({
            'userId': {'$oid': oid},
            'porcentaje': round(pct, 13)
        })

    # Verificar suma
    total = sum(p['porcentaje'] for p in participaciones)
    if abs(total - 100) > 0.0001:
        print(f'WARNING: periodo {fecha} suma={total}')

    result.append({
        'fechaInicio': {'$date': fecha},
        'motivo': motivo,
        'participaciones': participaciones,
        'creadoEn': {'$date': fecha}
    })

print(f'Generados {len(result)} periodos')
for r in result:
    total = sum(p['porcentaje'] for p in r['participaciones'])
    print(f"{r['motivo'][:40]}: {total:.10f}")

with open(r'c:\Users\jpsga\anestesiadelvalle\seed-group-periods.json', 'w', encoding='utf-8') as f:
    json.dump(result, f, ensure_ascii=False, indent=2)

